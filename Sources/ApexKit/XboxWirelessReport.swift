    /// Where Xbox Bluetooth firmware puts each button among its 15 bits; the gaps are unused.
    /// Games read these positions, not the descriptor (SDL's HIDAPI driver, which Wine and Steam
    /// use, among them).
    private static let buttonBits: [(GamepadButtons, Int)] = [
        (.a, 0), (.b, 1), (.x, 3), (.y, 4), (.leftBumper, 6), (.rightBumper, 7),
        (.back, 10), (.start, 11), (.guide, 12), (.leftStick, 13), (.rightStick, 14),
    ]

    /// Input report 1 (17 bytes including the ID):
    /// X Y Rx Ry (u16, 0 = left/up) | LT RT (10 bit) | hat (1-8 clockwise from up, 0 = centred) | buttons | share.
    public static func encode(_ s: GamepadState) -> Data {
        var r = [UInt8](repeating: 0, count: 17)
        r[0] = inputReportID
        put(&r, 1, axis(s.leftStick.x))
        put(&r, 3, axis(flipY(s.leftStick.y)))
        put(&r, 5, axis(s.rightStick.x))
        put(&r, 7, axis(flipY(s.rightStick.y)))
        put(&r, 9, trigger(s.leftTrigger))
        put(&r, 11, trigger(s.rightTrigger))
        r[13] = hat(s.buttons)
        var bits: UInt16 = 0
        for (b, i) in buttonBits where s.buttons.contains(b) { bits |= 1 << i }
        put(&r, 14, bits)
        return Data(r)
    }

    /// Decodes a rumble output report (ID 3) from a game. Payload after the ID:
    /// enable (bit0 weak, bit1 strong), LT, RT, strong, weak (0-100), duration (10 ms units,
    /// 0xFF = until changed), start delay, loop count.
    public static func decodeRumble(_ data: some RandomAccessCollection<UInt8>) -> Rumble? {
        var p = Array(data)
        if p.count == 9, p[0] == rumbleReportID { p.removeFirst() }
        guard p.count >= 8 else { return nil }
        let strong = p[0] & 0x02 != 0 ? min(p[3], 100) : 0
        let weak = p[0] & 0x01 != 0 ? min(p[4], 100) : 0
        let forever = p[5] == 0xFF || p[7] == 0xFF
        return Rumble(
            strong: UInt8(UInt16(strong) * 255 / 100),
            weak: UInt8(UInt16(weak) * 255 / 100),
            duration: forever ? nil : .milliseconds(Int(p[5]) * 10 * (Int(p[7]) + 1))
        )
    }

    public struct Rumble: Sendable, Equatable {
        /// Motor strengths, 0-255.
        public var strong: UInt8
        public var weak: UInt8
        /// nil = keep going until the next command.
        public var duration: Duration?

        public init(strong: UInt8, weak: UInt8, duration: Duration?) {
            self.strong = strong
            self.weak = weak
            self.duration = duration
        }
    }

    private static func axis(_ v: Int16) -> UInt16 { UInt16(Int32(v) + 32768) }
    // XInput Y is up-positive; Xbox HID is down-positive. Int16.min has no positive twin.
    private static func flipY(_ v: Int16) -> Int16 { v == .min ? .max : -v }
    private static func trigger(_ v: UInt8) -> UInt16 { UInt16((UInt32(v) * 1023 + 127) / 255) }

    private static func hat(_ b: GamepadButtons) -> UInt8 {
        // Opposite directions cancel out.
        let dx = (b.contains(.dpadRight) ? 1 : 0) - (b.contains(.dpadLeft) ? 1 : 0)
        let dy = (b.contains(.dpadUp) ? 1 : 0) - (b.contains(.dpadDown) ? 1 : 0)
        switch (dx, dy) {
        case (0, 1): return 1
        case (1, 1): return 2
        case (1, 0): return 3
        case (1, -1): return 4
        case (0, -1): return 5
        case (-1, -1): return 6
        case (-1, 0): return 7
        case (-1, 1): return 8
        default: return 0
        }
    }

    private static func put(_ r: inout [UInt8], _ i: Int, _ v: UInt16) {
        r[i] = UInt8(v & 0xFF)
        r[i + 1] = UInt8(v >> 8)
    }
}
